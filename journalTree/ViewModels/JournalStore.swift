import Foundation
import SwiftUI
import Combine
import WidgetKit

// MARK: - AppView
enum AppView { case tree, form }

// MARK: - JournalStore
final class JournalStore: ObservableObject {

    @Published private(set) var journals:       [Journal] = []
    @Published var selectedJournalID: UUID?
    @Published var activeView:        AppView   = .tree
    @Published var popupJournal:      Journal?

    private let key = "journaltree_v5"

    // MARK: Computed
    var happyCount: Int { journals.filter { $0.mood == .happy }.count }
    var sadCount:   Int { journals.filter { $0.mood == .sad   }.count }

    var selectedJournal: Journal? {
        guard let id = selectedJournalID else { return nil }
        return journals.first { $0.id == id }
    }

    // MARK: Init
    init() {
        load()
        if journals.isEmpty { seedSamples() }
    }

    // MARK: - CRUD
    func addJournal(title: String, content: String, mood: Mood) {
        guard journals.count < LeafLayout.totalLeaves else { return }
        let j = Journal(title: title, content: content, mood: mood)
        journals.append(j)
        selectedJournalID = j.id
        activeView = .tree
        save()
    }

    func deleteJournal(id: UUID) {
        journals.removeAll { $0.id == id }
        if selectedJournalID == id { selectedJournalID = nil }
        popupJournal = nil
        save()
    }

    // MARK: - Selection
    func toggleSelection(_ id: UUID) {
        selectedJournalID = (selectedJournalID == id) ? nil : id
        popupJournal = nil
    }

    func selectLeaf(_ journal: Journal) {
        selectedJournalID = journal.id
        popupJournal = journal
    }

    func dismissPopup() { popupJournal = nil }

    // MARK: - Nav
    func showForm() { activeView = .form }
    func showTree() { activeView = .tree }

    // MARK: - Persistence
    private func save() {
        guard let data = try? JSONEncoder().encode(journals) else { return }
        UserDefaults.standard.set(data, forKey: key)
        updateWidgetData()
    }

    private func updateWidgetData() {
        let widgetData: [[String: Any]] = journals.enumerated().compactMap { index, journal in
            guard index < LeafLayout.positions.count else { return nil }
            let pos = LeafLayout.positions[index]
            
            let imageName: String = {
                switch journal.mood {
                case .happy:        return "leafYellow"
                case .sad:          return "leafBlue"
                case .angry:        return "leafRed"
                case .disappointed: return "leafPurple"
                case .fear:         return "leafGreen"
                }
            }()
            
            return [
                "image": imageName,
                "xOffset": Double(pos.x - 0.5),
                "yOffset": Double(pos.y - 0.5),
                "rotation": Double(pos.rotation)
            ]
        }
        
        if let sharedDefaults = UserDefaults(suiteName: "group.com.nanda.journalTree") {
            if let jsonData = try? JSONSerialization.data(withJSONObject: widgetData) {
                sharedDefaults.set(jsonData, forKey: "widget_leaves_json")
                WidgetCenter.shared.reloadAllTimelines()
            }
        }
    }

    private func load() {
        guard let data = UserDefaults.standard.data(forKey: key),
              let decoded = try? JSONDecoder().decode([Journal].self, from: data)
        else { return }
        journals = decoded
    }

